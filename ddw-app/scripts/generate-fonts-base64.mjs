// Build-time codegen: embed the Familjen Grotesk WOFF2 files as base64 so the
// print HTML can ship a self-contained @font-face without runtime file reads.
// Reads the fontsource package once at build time and writes src/card/fontsBase64.ts.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

// The two weights the card uses, resolved from the project root.
const FONTS = [
    {
        const: 'FAMILIEN_GROTESK_400_BASE64',
        path: './node_modules/@fontsource/familjen-grotesk/files/familjen-grotesk-latin-400-normal.woff2',
    },
    {
        const: 'FAMILIEN_GROTESK_700_BASE64',
        path: './node_modules/@fontsource/familjen-grotesk/files/familjen-grotesk-latin-700-normal.woff2',
    },
];

// Resolve relative to the scripts/ directory's parent (the app root).
function resolveFromRoot(relative) {
    return resolve(dirname(fileURLToPath(import.meta.url)), '..', relative);
}

// Base64-encode each font's bytes for embedding in the HTML <style>.
function encodeFont(path) {
    return readFileSync(resolveFromRoot(path)).toString('base64');
}

// Write the generated module so imports only touch stable, checked-in code.
function writeModule() {
    const lines = FONTS.map(
        (font) => `export const ${font.const} = '${encodeFont(font.path)}';`,
    );
    const outDir = resolveFromRoot('src/card');
    mkdirSync(outDir, { recursive: true });
    writeFileSync(
        resolveFromRoot('src/card/fontsBase64.ts'),
        `// AUTO-GENERATED by scripts/generate-fonts-base64.mjs — do not edit by hand.\n` +
            `// Base64-encoded Familien Grotesk WOFF2 for the print HTML @font-face.\n\n` +
            lines.join('\n') +
            '\n',
    );
    console.log('Wrote src/card/fontsBase64.ts');
}

writeModule();